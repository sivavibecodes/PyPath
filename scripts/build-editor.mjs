#!/usr/bin/env node
/**
 * Bundles editor-src/index.ts (CodeMirror 6) into a single minified IIFE and
 * writes it as a TS string constant, so the editor WebView works fully offline
 * with no file:// or network access at all.
 */
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'src', 'components', 'editor', 'generated', 'editorBundle.ts');

async function writeBundle(code, note) {
  await mkdir(path.dirname(OUT), { recursive: true });
  await writeFile(
    OUT,
    `// AUTO-GENERATED by scripts/build-editor.mjs — do not edit.\n// ${note}\nexport const EDITOR_BUNDLE: string = ${JSON.stringify(code)};\n`,
  );
}

try {
  const { build } = await import('esbuild');
  const result = await build({
    entryPoints: [path.join(ROOT, 'editor-src', 'index.ts')],
    bundle: true,
    minify: true,
    format: 'iife',
    target: ['es2019', 'safari13', 'chrome80'],
    write: false,
    legalComments: 'none',
  });
  const code = result.outputFiles[0].text;
  await writeBundle(code, `CodeMirror 6 bundle, ${(code.length / 1024).toFixed(0)} KB`);
  console.log(`[build-editor] wrote ${path.relative(ROOT, OUT)} (${(code.length / 1024).toFixed(0)} KB)`);
} catch (err) {
  console.warn('[build-editor] build failed — writing empty placeholder:', err?.message ?? err);
  await writeBundle('', 'PLACEHOLDER: run `npm run assets:editor`');
}
