#!/usr/bin/env node
/**
 * Vendors the Pyodide runtime (+ selected packages and their dependencies) into
 * assets/pyodide/ and generates src/engine/assets/pyodideManifest.generated.ts
 * with static require() calls Metro can bundle.
 *
 * Usage:
 *   node scripts/fetch-pyodide.mjs                 # core + default packages
 *   node scripts/fetch-pyodide.mjs --if-missing    # postinstall: skip if up to date
 *   PYPATH_BUNDLE_PACKAGES=numpy,pandas,matplotlib node scripts/fetch-pyodide.mjs
 *   PYODIDE_VERSION=0.27.5 node scripts/fetch-pyodide.mjs
 *
 * Files are stored as "<sanitised_name>.bin" because (a) Metro must not compile
 * pyodide.js as app source and (b) Android raw resources drop the extension, so
 * pyodide.asm.js / pyodide.asm.wasm would otherwise collide.
 */
import { createHash } from 'node:crypto';
import { existsSync } from 'node:fs';
import { mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const VERSION = process.env.PYODIDE_VERSION ?? '0.27.5';
const CDN = `https://cdn.jsdelivr.net/pyodide/v${VERSION}/full/`;
const OUT_DIR = path.join(ROOT, 'assets', 'pyodide');
const MANIFEST = path.join(ROOT, 'src', 'engine', 'assets', 'pyodideManifest.generated.ts');
const STAMP = path.join(OUT_DIR, '.stamp.json');

const CORE_FILES = ['pyodide.js', 'pyodide.asm.js', 'pyodide.asm.wasm', 'python_stdlib.zip', 'pyodide-lock.json'];
/** Default offline set: Pandas/NumPy for Finance & Data tracks, BeautifulSoup for Marketing scraping lessons. */
const DEFAULT_PACKAGES = ['numpy', 'pandas', 'beautifulsoup4'];
const packages = (process.env.PYPATH_BUNDLE_PACKAGES ?? DEFAULT_PACKAGES.join(','))
  .split(',')
  .map((s) => s.trim().toLowerCase())
  .filter(Boolean);
const ifMissing = process.argv.includes('--if-missing');

const bundledName = (file) => `${file.toLowerCase().replace(/[^a-z0-9]/g, '_')}.bin`;
const sha256 = (buf) => createHash('sha256').update(buf).digest('hex');

async function download(url, attempts = 3) {
  for (let i = 1; ; i++) {
    try {
      const res = await fetch(url);
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      return Buffer.from(await res.arrayBuffer());
    } catch (e) {
      if (i >= attempts) throw new Error(`Failed to download ${url}: ${e.message}`);
      await new Promise((r) => setTimeout(r, 750 * i));
    }
  }
}

function resolvePackages(lock, names) {
  const byNormalised = new Map(Object.entries(lock.packages).map(([k, v]) => [k.toLowerCase().replace(/_/g, '-'), v]));
  const seen = new Map();
  const stack = [...names];
  while (stack.length) {
    const name = stack.pop().toLowerCase().replace(/_/g, '-');
    if (seen.has(name)) continue;
    const pkg = lock.packages[name] ?? byNormalised.get(name);
    if (!pkg) throw new Error(`Unknown Pyodide package "${name}" for v${VERSION}`);
    seen.set(name, pkg);
    stack.push(...(pkg.depends ?? []));
  }
  return [...seen.values()];
}

async function writeManifest(files, pkgNames) {
  const rel = (f) => path.relative(path.dirname(MANIFEST), path.join(OUT_DIR, bundledName(f))).split(path.sep).join('/');
  const entries = files.map((f) => `  { name: ${JSON.stringify(f)}, module: require(${JSON.stringify(rel(f))}) },`).join('\n');
  await mkdir(path.dirname(MANIFEST), { recursive: true });
  await writeFile(
    MANIFEST,
    `// AUTO-GENERATED by scripts/fetch-pyodide.mjs — do not edit by hand.
/* eslint-disable @typescript-eslint/no-require-imports */
export const PYODIDE_VERSION = ${JSON.stringify(VERSION)};
export const PYODIDE_BUNDLED_PACKAGES: readonly string[] = ${JSON.stringify(pkgNames)};
export const PYODIDE_FILES: ReadonlyArray<{ name: string; module: number }> = [
${entries}
];
`,
  );
}

async function writeEmptyManifest() {
  await mkdir(path.dirname(MANIFEST), { recursive: true });
  await writeFile(
    MANIFEST,
    `// AUTO-GENERATED by scripts/fetch-pyodide.mjs — do not edit by hand.
// No bundled files: the engine falls back to the CDN (online-only).
export const PYODIDE_VERSION = ${JSON.stringify(VERSION)};
export const PYODIDE_BUNDLED_PACKAGES: readonly string[] = [];
export const PYODIDE_FILES: ReadonlyArray<{ name: string; module: number }> = [];
`,
  );
}

async function main() {
  const wanted = { version: VERSION, packages: [...packages].sort() };
  if (ifMissing && existsSync(STAMP) && existsSync(MANIFEST)) {
    const stamp = JSON.parse(await readFile(STAMP, 'utf8'));
    if (JSON.stringify(stamp.wanted) === JSON.stringify(wanted)) {
      console.log(`[fetch-pyodide] Pyodide ${VERSION} already vendored — skipping.`);
      return;
    }
  }

  await mkdir(OUT_DIR, { recursive: true });
  console.log(`[fetch-pyodide] Pyodide ${VERSION} from ${CDN}`);

  const fileNames = [];
  for (const file of CORE_FILES) {
    const buf = await download(CDN + file);
    await writeFile(path.join(OUT_DIR, bundledName(file)), buf);
    fileNames.push(file);
    console.log(`  ✓ ${file} (${(buf.length / 1048576).toFixed(1)} MB)`);
  }

  const lock = JSON.parse(await readFile(path.join(OUT_DIR, bundledName('pyodide-lock.json')), 'utf8'));
  const resolved = resolvePackages(lock, packages);
  for (const pkg of resolved) {
    const target = path.join(OUT_DIR, bundledName(pkg.file_name));
    let buf = existsSync(target) ? await readFile(target) : null;
    if (!buf || (pkg.sha256 && sha256(buf) !== pkg.sha256)) {
      buf = await download(CDN + pkg.file_name);
      if (pkg.sha256 && sha256(buf) !== pkg.sha256) throw new Error(`Checksum mismatch for ${pkg.file_name}`);
      await writeFile(target, buf);
    }
    fileNames.push(pkg.file_name);
    console.log(`  ✓ ${pkg.name} ${pkg.version} (${(buf.length / 1048576).toFixed(1)} MB)`);
  }

  // Sanity: sanitised names must be unique (Android raw resources are flat).
  const names = fileNames.map(bundledName);
  if (new Set(names).size !== names.length) throw new Error('Asset name collision after sanitising');

  // Remove stale files from previous versions / package sets.
  const keep = new Set([...names, '.stamp.json']);
  for (const f of await readdir(OUT_DIR)) if (!keep.has(f)) await rm(path.join(OUT_DIR, f), { force: true });

  await writeManifest(fileNames, resolved.map((p) => p.name).sort());
  await writeFile(STAMP, JSON.stringify({ wanted, files: fileNames }, null, 2));
  console.log(`[fetch-pyodide] Done: ${fileNames.length} files → assets/pyodide, manifest updated.`);
}

main().catch(async (e) => {
  console.warn(`[fetch-pyodide] ${e.message}`);
  if (!existsSync(MANIFEST) || !existsSync(STAMP)) {
    console.warn('[fetch-pyodide] Writing CDN-fallback manifest; re-run `npm run assets:pyodide` when online.');
    await writeEmptyManifest();
  }
  // Never fail `npm install` because of a flaky network.
  process.exit(ifMissing ? 0 : 1);
});
